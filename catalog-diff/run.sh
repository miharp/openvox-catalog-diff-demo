#!/usr/bin/env bash
# Diff the catalogs of every node under catalog-diff/nodes/ between two git refs.
#
#   catalog-diff/run.sh [BASE_REF] [HEAD_REF]
#
# BASE_REF is deployed as the `production` environment and HEAD_REF as
# `change`. Set KEEP=1 to leave the stack running afterwards.
#
# Exit status is 0 when every catalog compiled, whether or not anything
# changed, and 1 otherwise. The JSON report and Catalog Diff's full output
# are left in catalog-diff/.work/report/.

set -euo pipefail

base_ref="${1:-production}"
head_ref="${2:-HEAD}"

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(git -C "$here" rev-parse --show-toplevel)"
work="$here/.work"
puppet=/opt/puppetlabs/bin/puppet
code=/etc/puppetlabs/code/environments
environments=(production change)

compose() {
  docker compose --project-directory "$here" -f "$here/compose.yaml" -f "$work/nodes.yaml" "$@"
}
step() { printf '\n==> %s\n' "$*"; }

step "Deploying $base_ref as production and $head_ref as change"
rm -rf "$work"
mkdir -p "$work/environments/production" "$work/environments/change" "$work/report"
git -C "$repo" archive "$base_ref" | tar -x -C "$work/environments/production"
git -C "$repo" archive "$head_ref" | tar -x -C "$work/environments/change"

# One agent container per directory under nodes/. Each directory holds the
# csr_attributes.yaml that asks for the node's role, and optionally a
# facts.yaml of external facts.
nodes=()
{
  echo '# Generated by run.sh from the directories under nodes/.'
  echo 'services:'
  for dir in "$here"/nodes/*/; do
    node="$(basename "$dir")"
    nodes+=("$node")
    cat <<EOF
  $node:
    image: ghcr.io/openvoxproject/openvoxagent:8
    hostname: $node
    entrypoint: ["sleep", "infinity"]
    volumes:
      - ./nodes/$node/csr_attributes.yaml:/etc/puppetlabs/puppet/csr_attributes.yaml:ro
EOF
    if [[ -f "$dir/facts.yaml" ]]; then
      echo "      - ./nodes/$node/facts.yaml:/etc/puppetlabs/facter/facts.d/node.yaml:ro"
    fi
    cat <<EOF
    depends_on:
      openvoxdb:
        condition: service_healthy
EOF
  done
} > "$work/nodes.yaml"
echo "Nodes: ${nodes[*]}"

cleanup() {
  if [[ "${KEEP:-0}" != 1 ]]; then
    step 'Tearing down'
    compose down --volumes --remove-orphans
  fi
}
trap cleanup EXIT

for env in "${environments[@]}"; do
  [[ -f "$work/environments/$env/Puppetfile" ]] || continue
  step "Installing the modules in the $env Puppetfile"
  # The server image ships r10k. This runs before the server starts, because
  # the image caches environments for good once it has read them. Root, so
  # it can write to the bind mount; then the modules go back to the user
  # running this script.
  compose run --rm -T --no-deps -u root --entrypoint bash openvoxserver -euo pipefail -c "
    r10k puppetfile install --verbose --puppetfile $code/$env/Puppetfile --moduledir $code/$env/modules
    chown -R $(id -u):$(id -g) $code/$env/modules
  "
done

step 'Starting the server, OpenVoxDB, and agents'
compose up --detach --wait

step 'Running each agent once in noop mode, so OpenVoxDB has its facts'
for node in "${nodes[@]}"; do
  echo "--- $node"
  compose exec -T "$node" "$puppet" agent --test --noop --server puppet --certname "$node"
done

step 'Waiting for OpenVoxDB to store facts and a catalog for each agent'
stored_nodes() {
  compose exec -T openvoxserver bash -c '
    ssl=/etc/puppetlabs/puppet/ssl
    curl -sS -G https://openvoxdb:8081/pdb/query/v4 \
      --cacert "$ssl/certs/ca.pem" --cert "$ssl/certs/puppet.pem" --key "$ssl/private_keys/puppet.pem" \
      --data-urlencode "query=nodes[count()] { catalog_timestamp is not null and facts_timestamp is not null }"
  '
}
for attempt in {1..30}; do
  stored="$(stored_nodes)"
  [[ "$stored" == *"\"count\":${#nodes[@]}"* ]] && break
  if (( attempt == 30 )); then
    echo "OpenVoxDB has not stored every agent: $stored" >&2
    exit 1
  fi
  sleep 2
done
echo "OpenVoxDB has facts and a catalog for ${#nodes[@]} nodes"

step 'Preparing the Catalog Diff node'
compose exec -T catalog-diff bash -euo pipefail -c "
  export DEBIAN_FRONTEND=noninteractive
  apt-get -qq update
  apt-get -qq install -y openvoxdb-termini >/dev/null
  printf '[main]\nserver_urls = https://openvoxdb:8081\n' > /etc/puppetlabs/puppet/puppetdb.conf
  $puppet ssl bootstrap --server puppet --certname catalog-diff
  $puppet module install puppet-catalog_diff
"

step "Comparing each node's catalog compiled from production and from change"
# Catalog Diff's own output is long, so it goes to a file and the report is
# summarized instead. It is shown if the command itself fails.
if ! compose exec -T catalog-diff "$puppet" catalog diff \
  puppet:8140/production puppet:8140/change \
  --certname catalog-diff \
  --filter_old_env \
  --certless \
  --show_resource_diff \
  --content_diff \
  --color false \
  --output_report /report/report.json > "$work/report/diff.txt" 2>&1; then
  cat "$work/report/diff.txt"
  exit 1
fi

echo "Full output and JSON report: ${work#"$repo"/}/report/"

# Tear down first so the summary is the last thing on screen.
trap - EXIT
cleanup

echo
"$here/summary.py" --text "$work/report/report.json"
